"""Собрать значки и палитры из bell.svg и palette.json. Требуются Pillow и resvg-py."""

import json
import re
from io import BytesIO
from pathlib import Path
import xml.etree.ElementTree as ET

import resvg_py
from PIL import Image, ImageColor, ImageDraw, ImageOps

root = Path('assets/icons')
svg = ET.parse(root / 'bell.svg').getroot()
resize = Image.Resampling.LANCZOS
masks = {}
for path in svg:
    markup = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024"><path transform="{path.attrib.get("transform", "")}" d="{path.attrib["d"]}"/></svg>'
    masks[path.attrib['id']] = Image.open(BytesIO(resvg_py.svg_to_bytes(svg_string=markup))).convert('RGBA').getchannel('A')


def paint(mask, color):
    image = Image.new('RGBA', mask.size, color)
    image.putalpha(mask)
    return image


def srgb(rgb):
    return 'srgb:' + ','.join(f'{c/255:.5f}' for c in rgb) + ',1.00000'


def gradient(start, stop):
    return {'linear-gradient': [srgb(start), srgb(stop)],
            'orientation': {'start': {'x': 0, 'y': 0}, 'stop': {'x': 1, 'y': 1}}}


def diagonal(size):
    mask = Image.new('L', (size, size))
    draw = ImageDraw.Draw(mask)
    for offset in range(2 * size - 1):
        draw.line((offset, 0, 0, offset), fill=round(255 * offset / (2 * size - 2)))
    return mask


ramp = diagonal(1024)


themes = json.loads((root / 'palette.json').read_text(encoding='utf-8'))
ids = [theme['id'] for theme in themes]
assert ids == json.loads((root / 'icons.json').read_text())
choices = []
for theme in themes:
    mono = ', mono: true' if theme['id'] == 'mono' else ''
    choices.append(f"  ThemeChoice('{theme['id']}', '{theme['name']}', Color(0xFF{theme['seed']}){mono}),")
Path('lib/core/palette_choices.dart').write_text(
    "// Generated by scripts/icons/render_bell.py from assets/icons/palette.json.\npart of 'palette.dart';\n\n"
    + "const _themeChoices = [\n" + "\n".join(choices) + "\n];\n", encoding='utf-8', newline='\n')
drawable = root / 'android/drawable-nodpi'
silhouette = Image.new('RGBA', (1024, 1024))
for mask in masks.values():
    silhouette.alpha_composite(paint(mask, 'white'))
bounds = silhouette.getbbox()
body = Image.new('RGBA', silhouette.size)
for part in ('dome', 'lip'):
    body.alpha_composite(paint(masks[part], 'white'))
body.crop(bounds).save(root / 'bell.png')
paint(masks['clapper'], 'white').crop(bounds).save(root / 'clapper.png')
silhouette.resize((432,432), resize).save(drawable / 'ic_mono_shared.png')
palettes = json.loads(Path('scripts/icons/artwork_palettes.json').read_text(encoding='utf-8'))


for theme in themes:
    key = theme['id']
    light = palettes[key]['light']
    dark = palettes[key]['dark']
    background = ImageOps.colorize(ramp, light['surface'], light['primaryContainer'])
    ios = root / 'ios' / ('AppIcon.icon' if key == 'default' else f'Icon_{key}.icon')
    doc = json.loads((ios / 'icon.json').read_text())
    def surface(a, b):
        return gradient(ImageColor.getrgb(a), ImageColor.getrgb(b))
    doc['fill-specializations'] = [
        {'value': surface(light['surface'], light['primaryContainer'])},
        {'appearance': 'dark', 'value': surface(dark['surfaceContainer'], dark['surface'])},
    ]
    picture = Image.new('RGBA', (1024, 1024))
    layers = []
    for name, mask in masks.items():
        front = light['primary'] if name == 'dome' else light['onPrimaryContainer']
        edge = light['onSurfaceVariant'] if name == 'dome' else light['onSurface']
        # Icon Composer lights the layers on-device. Android uses a broad tonal transition.
        paint(mask, front).save(ios / 'Assets' / (name + '.png'))
        layer = ImageOps.colorize(ramp, front, edge).convert('RGBA')
        layer.putalpha(mask)
        picture.alpha_composite(layer)
        dark_fill = surface(dark['onPrimaryContainer'], dark['primary'] if name == 'dome' else dark['onSurfaceVariant'])
        mono = (226, 226, 226) if name == 'lip' else (255, 255, 255)
        layers.append({'image-name': name + '.png', 'name': name, 'glass': name == 'dome',
                       'fill-specializations': [
                           {'appearance': 'dark', 'value': dark_fill},
                           {'appearance': 'tinted', 'value': {'solid': srgb(mono)}},
                       ]})
    # A separate rear plane gives the clapper native depth under the shell.
    doc['groups'] = [
        {'layers': parts, 'translucency': {'enabled': False, 'value': .1}}
        for parts in (layers[:1], layers[1:])
    ]
    (ios / 'icon.json').write_text(json.dumps(doc, indent=2) + '\n', encoding='utf-8', newline='\n')
    suffix = re.sub(r'[A-Z]', lambda m: '_' + m[0].lower(), key)
    background.resize((432, 432), resize).save(drawable / f'ic_bg_{suffix}.png')
    picture.resize((432,432), resize).save(drawable / f'ic_fg_{suffix}.png')
    picture = Image.alpha_composite(background.convert('RGBA'), picture)
    name = 'ic_launcher' if key == 'default' else 'ic_launcher_' + suffix
    for density, size in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
        for ending in ['', '_round']:
            mask = Image.new('L', picture.size)
            ImageDraw.Draw(mask).rounded_rectangle((0, 0, 1023, 1023), radius=512 if ending else 228, fill=255)
            picture.putalpha(mask)
            picture.resize((size, size), resize).save(root / 'android' / ('mipmap-' + density) / (name + ending + '.png'))
